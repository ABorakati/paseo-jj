/**
 * Builds client/vendor/pierre.js from build/pierre-entry.mjs.
 *
 * Paseo's plugin compiler resolves the plugin's own imports but not a
 * dependency's transitive graph, and Pierre's worker module imports `lru_map`,
 * which that compiler refuses. Bundling Pierre here leaves Paseo a single local
 * file to inline, and keeps the editor's own specifiers out of its resolver.
 *
 * Run it whenever @pierre/diffs or build/pierre-entry.mjs changes:
 *   npm run build:pierre
 */
import { build } from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(dir, "..");

const result = await build({
 entryPoints: [path.join(dir, "pierre-entry.mjs")],
 outfile: path.join(root, "client/vendor/pierre.js"),
 bundle: true,
 // CommonJS, not ESM: parts of Pierre's graph reach React through `require`, and
 // an ESM output with an external React turns that into a runtime throw. Both
 // Paseo and the local test harness bundle this file themselves, so the format
 // only has to be one esbuild can interop with.
 format: "cjs",
 platform: "browser",
 target: "es2022",
 minify: true,
 legalComments: "none",
 // React is a host module: the app supplies the one instance every plugin
 // shares, and a second copy inlined here breaks every hook in the editor. The
 // bundle keeps the import and lets the host resolve it. react-dom is not a host
 // module, so it stays inside; its own `react` import is external too.
 external: ["react", "react/jsx-runtime", "react-native"],
 // Pierre adopts its core stylesheet from a string rather than a link tag, so
 // no CSS asset may be emitted beside the bundle.
 loader: { ".css": "text" },
 define: { "process.env.NODE_ENV": '"production"' },
 banner: {
  js: "/* Generated by build/vendor-pierre.mjs from build/pierre-entry.mjs. Do not edit. */",
 },
 metafile: true,
});

const [output] = Object.values(result.metafile.outputs);
console.log(`client/vendor/pierre.js: ${(output.bytes / 1024 / 1024).toFixed(2)}MB`);
